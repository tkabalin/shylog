import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { format, resolveConfig } from "prettier"

// Writes src/zones.ts from tzdata's public-domain zone.tab and zonenow.tab:
// one row per clock a country keeps today, with the coordinates of its main
// city. Run `node packages/core/scripts/zones.ts [tzdata folder]` after a
// tzdata update; Node's own time zone data should be as new.

const folder = process.argv[2] ?? "/usr/share/zoneinfo"
const rows = (file: string) =>
  readFileSync(`${folder}/${file}`, "utf8")
    .split("\n")
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => line.split("\t"))

// ±DDMM[SS] then ±DDDMM[SS], so 2 or 3 degree digits for each half.
function degrees(text: string, degreeDigits: number) {
  const sign = text[0] === "-" ? -1 : 1
  const d = Number(text.slice(1, 1 + degreeDigits))
  const m = Number(text.slice(1 + degreeDigits, 3 + degreeDigits))
  const s = Number(text.slice(3 + degreeDigits) || 0)
  return Math.round(sign * (d + m / 60 + s / 3600) * 100) / 100
}

// Zones whose UTC offsets agree through this year keep the same clock now,
// such as Indiana's eight and New York, so each counts once.
const year = new Date().getUTCFullYear()
function clockKey(zone: string) {
  const offset = new Intl.DateTimeFormat("en-US", {
    timeZone: zone,
    timeZoneName: "longOffset",
  })
  return Array.from({ length: 24 }, (_, i) =>
    offset.format(Date.UTC(year, i >> 1, i & 1 ? 15 : 1, 12))
  ).join()
}

// zonenow.tab names one zone per clock, its most populous, so that zone's
// city stands for the others; otherwise zone.tab's first, by its ordering.
const preferred = new Set(rows("zonenow.tab").map(([, , zone]) => zone))
const kept = new Map<string, (string | number)[]>()
for (const [country, coordinates, zone] of rows("zone.tab")) {
  const at = coordinates.slice(1).search(/[+-]/) + 1
  const row = [
    country,
    degrees(coordinates.slice(0, at), 2),
    degrees(coordinates.slice(at), 3),
    zone,
  ]
  const key = `${country} ${clockKey(zone)}`
  if (!kept.has(key) || preferred.has(zone)) {
    if (!preferred.has(kept.get(key)?.[3] as string)) kept.set(key, row)
  }
}
// Where a country has any of zonenow's populous clocks, only those count,
// so stations such as Greenland's Thule and Danmarkshavn don't outvote Nuuk.
const rowsKept = [...kept.values()]
const populous = new Set(
  rowsKept.filter((row) => preferred.has(row[3] as string)).map((r) => r[0])
)
const table = rowsKept
  .filter((row) => !populous.has(row[0]) || preferred.has(row[3] as string))
  .sort(
    (a, b) =>
      String(a[0]).localeCompare(String(b[0])) ||
      String(a[3]).localeCompare(String(b[3]))
  )

const file = fileURLToPath(new URL("../src/zones.ts", import.meta.url))
const source = `// Generated by scripts/zones.ts from tzdata's zone.tab and zonenow.tab;
// don't edit by hand. Each clock a country keeps today, with the latitude
// and longitude of its main city, for sunset where a site has no position.
export const zoneCities: readonly (readonly [
  country: string,
  latitude: number,
  longitude: number,
  zone: string,
])[] = ${JSON.stringify(table)}
`
writeFileSync(
  file,
  await format(source, { ...(await resolveConfig(file)), filepath: file })
)
